import { test, expect } from '@playwright/test';
import { env } from '../../core/be/src/config/env.js';
const apiRoot = `http://127.0.0.1:${process.env.E2E_API_PORT || '3100'}${env.API_PREFIX}`;
test('S4-23/25/27: nhóm kỳ, so sánh, cơ cấu và tab hội viên dùng bộ lọc đã áp dụng', async ({ page, request }, info) => {
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  const session = await request.post(`${apiRoot}/auth/login`, { data: { email: env.SEED_ADMIN_EMAIL, password: env.SEED_ADMIN_PASSWORD } });
  expect(session.status()).toBe(200);
  const token = (await session.json()).data.accessToken;
  await page.addInitScript((accessToken) => localStorage.setItem('scms.auth', JSON.stringify({ state: { accessToken }, version: 0 })), token);
  await page.goto('/reports');
  await expect(page.getByRole('heading', { name: 'Báo cáo trung tâm' })).toBeVisible();
  await expect(page.getByText('So với khoảng liền trước cùng số ngày')).toBeVisible();
  await page.getByRole('combobox', { name: 'Khoảng nhanh', exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Năm nay', { exact: true }).click();
  const applied = page.waitForResponse((res) => res.url().includes('/reports/dashboard?') && res.url().includes('groupBy=month'));
  await page.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  expect((await applied).status()).toBe(200);
  await expect(page.getByText('Cơ cấu doanh thu và xếp hạng')).toBeVisible();
  await expect(page.getByRole('img', { name: /Biểu đồ cột theo kỳ/ })).toBeVisible();
  await page.getByRole('combobox', { name: 'Chiều cơ cấu' }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Top lớp', { exact: true }).click();
  const members = page.waitForResponse((res) => res.url().includes('/reports/members?') && res.url().includes('groupBy=month'));
  await page.getByRole('tab', { name: 'Hội viên & đăng ký', exact: true }).click();
  expect((await members).status()).toBe(200);
  await expect(page.getByText('Hội viên và tình trạng đăng ký')).toBeVisible();
  const file = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Xuất báo cáo', exact: true }).click();
  expect((await file).suggestedFilename()).toMatch(/^members-.*\.xlsx$/u);
  await page.screenshot({ path: info.outputPath('sprint4-member-reports.png'), fullPage: true });
  expect(errors).toEqual([]);
});
